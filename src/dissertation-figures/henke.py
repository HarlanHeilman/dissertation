NA = 6.02214076e23
def n_compound(E, parts, rho):
    """parts: list of (table, count, molar_mass); rho g/cm3."""
    M = sum(c * m for _, c, m in parts)
    lam = 1.23984198e-4 / E  # cm
    f1 = sum(c * np.interp(E, t[:, 0], t[:, 1]) for t, c, _ in parts)
    f2 = sum(c * np.interp(E, t[:, 0], t[:, 2]) for t, c, _ in parts)
    nmol = rho * NA / M
    k = RE * lam ** 2 * nmol / (2 * np.pi)
    return 1 - k * f1 + 1j * k * f2
